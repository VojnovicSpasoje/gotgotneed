# Downloads the app's web fonts from Google Fonts into fonts/ and writes fonts/fonts.css,
# so the site and the Android app never contact Google when they open.
# Runs on GitHub Actions (workflow "Vendor fonts"); the fonts' licences (SIL OFL / Apache) allow this.
import os, re, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = open(os.path.join(ROOT, 'tools', 'fonts-url.txt')).read().strip()
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36'  # woff2
get = lambda u: urllib.request.urlopen(urllib.request.Request(u, headers={'User-Agent': UA}), timeout=60).read()

css = get(URL).decode()
out_dir = os.path.join(ROOT, 'fonts'); os.makedirs(out_dir, exist_ok=True)
for f in os.listdir(out_dir):
    if f.endswith('.woff2'): os.remove(os.path.join(out_dir, f))
blocks, n = [], 0
for m in re.finditer(r'(/\* ([\w-]+) \*/\s*)?@font-face \{(.*?)\}', css, re.S):
    subset, body = m.group(2) or 'all', m.group(3)
    fam = re.search(r"font-family: '([^']+)'", body).group(1)
    wt = re.search(r'font-weight: ([\d ]+);', body).group(1).replace(' ', '-')
    src = re.search(r'url\((https://[^)]+)\)', body).group(1)
    name = re.sub(r'[^a-z0-9]+', '-', fam.lower()) + '-' + wt + '-' + subset + '.woff2'
    open(os.path.join(out_dir, name), 'wb').write(get(src)); n += 1
    blocks.append('/* ' + subset + ' */\n@font-face {' + body.replace(src, name) + '}')
open(os.path.join(out_dir, 'fonts.css'), 'w').write('/* Generated by tools/vendor-fonts.py from Google Fonts – do not edit. */\n' + '\n'.join(blocks) + '\n')
print('fonts:', n)
